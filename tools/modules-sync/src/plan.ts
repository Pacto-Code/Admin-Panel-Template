import { resolveModules, type ModuleManifest, type StoreConfigInput } from "@platform/core";

const HEADER = "// GENERATED by pnpm modules:sync. Do not edit.";

/** Safe identifier from a kebab-case id: "my-mod" -> "myMod". */
const ident = (id: string): string => id.replace(/-([a-z0-9])/g, (_, ch: string) => ch.toUpperCase());

export function planSync(
  store: StoreConfigInput,
  available: Record<string, ModuleManifest>,
): { apiFile: string; adminFile: string } {
  const ids = resolveModules(store.modules, available).map((m) => m.id);

  const apiImports = ids.flatMap((id) => [
    `import { manifest as ${ident(id)}Manifest } from "@modules/${id}/manifest";`,
    `import { apiModule as ${ident(id)}ApiModule } from "@modules/${id}/api";`,
  ]);
  const adminImports = ids.flatMap((id) => [
    `import { manifest as ${ident(id)}Manifest } from "@modules/${id}/manifest";`,
    `import { adminModule as ${ident(id)}AdminModule } from "@modules/${id}/admin";`,
  ]);

  const apiEntries = ids.map(
    (id) => `  { id: "${id}", manifest: ${ident(id)}Manifest, apiModule: ${ident(id)}ApiModule },`,
  );
  const adminEntries = ids.map((id) => `  ${ident(id)}AdminModule,`);
  const manifestEntries = ids.map((id) => `  ${ident(id)}Manifest,`);

  const list = (entries: string[]) => (entries.length ? `\n${entries.join("\n")}\n` : "");

  const apiFile = [
    HEADER,
    `import type { Type } from "@nestjs/common";`,
    `import type { ModuleManifest } from "@platform/core";`,
    ...apiImports,
    "",
    `export const apiModules: { id: string; manifest: ModuleManifest; apiModule: Type }[] = [${list(apiEntries)}];`,
    "",
  ].join("\n");

  const adminFile = [
    HEADER,
    `import type { AdminModuleDef, ModuleManifest } from "@platform/core";`,
    ...adminImports,
    "",
    `export const adminModules: AdminModuleDef[] = [${list(adminEntries)}];`,
    `export const manifests: ModuleManifest[] = [${list(manifestEntries)}];`,
    "",
  ].join("\n");

  return { apiFile, adminFile };
}
